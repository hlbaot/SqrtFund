import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const contractsOutDir = path.join(rootDir, 'contracts', 'out');
const targetAbisDir = path.join(rootDir, 'src', 'lib', 'contracts', 'abis');

if (!fs.existsSync(targetAbisDir)) {
  fs.mkdirSync(targetAbisDir, { recursive: true });
}

const contractConfigs = [
  {
    jsonPath: path.join(contractsOutDir, 'MockUSDC.sol', 'MockUSDC.json'),
    outFile: 'mockUsdc.ts',
    varName: 'mockUsdcAbi',
  },
  {
    jsonPath: path.join(contractsOutDir, 'QFRound.sol', 'QFRound.json'),
    outFile: 'qfRound.ts',
    varName: 'qfRoundAbi',
  },
  {
    jsonPath: path.join(contractsOutDir, 'RoundFactory.sol', 'RoundFactory.json'),
    outFile: 'roundFactory.ts',
    varName: 'roundFactoryAbi',
  },
];

console.log('Extracting and syncing contract ABIs...');

for (const config of contractConfigs) {
  if (!fs.existsSync(config.jsonPath)) {
    console.error(`Artifact not found at ${config.jsonPath}. Did you run 'forge build'?`);
    process.exit(1);
  }

  const artifact = JSON.parse(fs.readFileSync(config.jsonPath, 'utf8'));
  const abiJson = JSON.stringify(artifact.abi, null, 2);

  const fileContent = `// Auto-generated by scripts/sync-abis.mjs. Do not edit directly.\nexport const ${config.varName} = ${abiJson} as const;\n`;

  fs.writeFileSync(path.join(targetAbisDir, config.outFile), fileContent, 'utf8');
  console.log(`✓ Generated ${config.outFile} (${config.varName})`);
}

// Write index.ts
const indexContent = `// Auto-generated by scripts/sync-abis.mjs\nexport * from './mockUsdc';\nexport * from './qfRound';\nexport * from './roundFactory';\n`;
fs.writeFileSync(path.join(targetAbisDir, 'index.ts'), indexContent, 'utf8');
console.log('✓ Generated index.ts');

console.log('ABI sync complete!');
